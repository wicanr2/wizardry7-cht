#!/usr/bin/env python3
# gen_monsters.py — SCENARIO.DBS 怪物名表抽取（013 追記三十四）
#
# 怪物記錄：232 bytes／隻、名字欄在 +72：[真名單][真名複][別名單][別名複]
# （每欄 \x00 結尾補齊）。Wiz7 的別名＝低鑑定度時顯示的名字。
# 產出 text/monsters.json（原文欄位進版控，使用者定案）。
import json, re, sys

DBS = 'workplace/original/wizar7/SCENARIO.DBS'
OUT = 'text/monsters.json'

d = open(DBS, 'rb').read()
R0, REC, NOFF = 225272, 232, 72

def names_at(r):
    b = d[r+NOFF:r+NOFF+104]
    names, pos = [], 0
    for _ in range(4):
        end = b.find(b'\x00', pos)
        if end < 0 or end > pos+24:
            return None
        nm = b[pos:end]
        if nm and not all(0x20 <= c <= 0x7e for c in nm):
            return None
        names.append(nm.decode())
        pos = end+1
        while pos < len(b) and b[pos] == 0:
            pos += 1
    return names

mons = []
r = R0
while r+NOFF < len(d):
    ns = names_at(r)
    if not ns or not any(ns):
        break
    mons.append({'idx': len(mons), 'rec': r, 'names': ns})
    r += REC

out = {
    'schema': 'wiz7-monsters/1',
    'note': 'SCENARIO.DBS 怪物名表（docs/re/013 追記三十四）。record=232B、'
            '名字欄 +72：[真名單數][真名複數][別名單數][別名複數]——別名＝低鑑定度顯示名。'
            'idx＝怪物編號（0 起，對應遊戲內部索引）；原文欄位進版控（使用者定案）。',
    'count': len(mons),
    'monsters': mons,
}
json.dump(out, open(OUT, 'w'), ensure_ascii=False, indent=1)
print(f'{OUT}: {len(mons)} 隻')

