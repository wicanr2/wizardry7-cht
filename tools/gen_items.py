# gen_items.py — SCENARIO.DBS 物品名表抽取（013 追記三十五）
#
# 物品記錄：72 bytes／件、名字欄 +0（\x00 結尾補齊）。
# 表：offset 896 起、417 件（BROKEN/ITEM＝idx 0 佔位）。
# 名字格式「MATERIAL/TYPE」＝材質/類型組合（LEATHER/CUIRASS 皮胸甲）。
# 產出 text/items.json（原文欄位進版控，使用者定案）。
import json

DBS = 'workplace/original/wizar7/SCENARIO.DBS'
OUT = 'text/items.json'
R0, REC = 896, 72

d = open(DBS, 'rb').read()

def name_at(r):
    b = d[r:r+32]
    end = b.find(b'\x00')
    if end < 0:
        return None
    s = b[:end]
    if not all(0x20 <= c <= 0x7e for c in s):
        return None
    return s.decode()

items = []
r = R0
while r+REC+32 < len(d):
    nm = name_at(r)
    if nm is None or len(nm) < 2:
        break
    items.append({'idx': len(items), 'rec': r, 'name': nm})
    r += REC

out = {
    'schema': 'wiz7-items/1',
    'note': 'SCENARIO.DBS 物品名表（docs/re/013 追記三十五）。record=72B、'
            '名字欄 +0（\x00 補齊）。idx＝物品編號（0 起，對應遊戲內部索引）；'
            'BROKEN/ITEM＝idx 0 佔位。原文欄位進版控（使用者定案）。',
    'count': len(items),
    'items': items,
}
json.dump(out, open(OUT, 'w'), ensure_ascii=False, indent=1)
print(f'{OUT}: {len(items)} 件')

